def compute_vowel_syllable_envelope(wav_16k: np.ndarray, n_frames: int) -> tuple:
    """Extract both the raw 24fps RMS envelope and the high-contrast F1/F2 Vowel Formant (300-2400 Hz)
    syllable open-close curve vowel_mod in [0, 1], which spikes to 1.0 on open vowel nuclei and drops to 0.0
    on every consonant (s/t/p/b/m/k) and inter-word boundary!
    """
    step = SR // FPS
    req = n_frames * step
    if len(wav_16k) < req:
        wav_16k = np.pad(wav_16k, (0, req - len(wav_16k)))
    raw_env = np.sqrt((wav_16k[:req].reshape(n_frames, step) ** 2).mean(1))

    b, a = butter(4, [300.0 / (0.5 * SR), 2400.0 / (0.5 * SR)], btype="band")
    wav_vowel = filtfilt(b, a, wav_16k[:req])
    v_env = np.sqrt((wav_vowel.reshape(n_frames, step) ** 2).mean(1))

    # Local syllable peak-valley expansion: subtract 5-frame (~0.2s) moving minimum and normalize by 9-frame maximum
    vmin = minimum_filter1d(v_env, size=5)
    vmax = maximum_filter1d(v_env, size=9)
    v_mod = np.clip((v_env - vmin * 0.82) / (vmax - vmin * 0.82 + 1e-4), 0.0, 1.0) ** 1.30
    v_mod[raw_env < 0.05 * (raw_env.max() + 1e-6)] = 0.0
    return raw_env, v_mod


def load_wav2lip_model(device: torch.device) -> Wav2Lip:
    model = Wav2Lip()
    ckpt = torch.load(WAV2LIP_GAN_PATH, map_location="cpu", weights_only=False)
    s = ckpt.get("state_dict", ckpt)
    new_s = {k.replace("module.", ""): v for k, v in s.items()}
    model.load_state_dict(new_s)
    model = model.to(device)
    model.eval()
    return model


