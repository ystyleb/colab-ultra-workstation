def detect_faces_in_frames(frames_rgb: list, who: str, two_shot: bool, landmarker):
    """Detect the rapping speaker's 468 face landmarks in every frame.
    In all two-shots generated by H3 (A02, A04, B03, B04), the active rapping speaker holding the microphone
    stands on the left half of the frame (x in [0 .. 0.58*W]), while the silent listener stands on the right.
    """
    H, W = frames_rgb[0].shape[:2]
    n_frames = len(frames_rgb)
    lms_px = [None] * n_frames
    mouth_open = np.zeros(n_frames, dtype=np.float32)

    for idx, rgb in enumerate(frames_rgb):
        chosen = None
        ox, oy, cw, ch = 0, 0, W, H
        if two_shot:
            ox = 0
            x1 = int(0.58 * W)
            ch = int(0.82 * H)
            cw = x1 - ox
            crop = np.ascontiguousarray(rgb[:ch, ox:x1])
            res_c = landmarker.detect(mp.Image(image_format=mp.ImageFormat.SRGB, data=crop))
            if res_c.face_landmarks:
                chosen = max(res_c.face_landmarks, key=lambda l: abs(l[152].y - l[10].y))
        if chosen is None:
            ox, oy, cw, ch = 0, 0, W, H
            mp_img = mp.Image(image_format=mp.ImageFormat.SRGB, data=rgb)
            res = landmarker.detect(mp_img)
            if res.face_landmarks:
                if two_shot:
                    left_faces = [l for l in res.face_landmarks if l[1].x < 0.58]
                    chosen = min(left_faces or res.face_landmarks, key=lambda l: l[1].x)
                else:
                    chosen = max(res.face_landmarks, key=lambda l: abs(l[152].y - l[10].y))
        if chosen is not None:
            pts = np.array([[p.x * cw + ox, p.y * ch + oy] for p in chosen], dtype=np.float32)
            lms_px[idx] = pts
            fh = max(1.0, abs(pts[152, 1] - pts[10, 1]))
            mouth_open[idx] = abs(pts[14, 1] - pts[13, 1]) / fh

    valid_indices = [i for i, x in enumerate(lms_px) if x is not None]
    if not valid_indices:
        raise RuntimeError(f"No face detected for who={who}")
    for i in range(n_frames):
        if lms_px[i] is None:
            prev_i = max([v for v in valid_indices if v < i], default=None)
            next_i = min([v for v in valid_indices if v > i], default=None)
            if prev_i is not None and next_i is not None:
                alpha = (i - prev_i) / float(next_i - prev_i)
                lms_px[i] = (1.0 - alpha) * lms_px[prev_i] + alpha * lms_px[next_i]
                mouth_open[i] = (1.0 - alpha) * mouth_open[prev_i] + alpha * mouth_open[next_i]
            elif prev_i is not None:
                lms_px[i] = lms_px[prev_i].copy()
                mouth_open[i] = mouth_open[prev_i]
            else:
                lms_px[i] = lms_px[next_i].copy()
                mouth_open[i] = mouth_open[next_i]

    return np.stack(lms_px, axis=0), mouth_open


def optimize_word_anchored_warp(
    raw_frames_bgr: list,
    raw_mo: np.ndarray,
    aud_env: np.ndarray,
    vowel_mod: np.ndarray,
    words_rel: list,
    target_dur: float,
    out_dur: float,
) -> tuple:
    """Stage 1 (Scheme B):
    1. Identify the exact dynamic mouth-opening span [raw_t0, raw_t1] in the 124-frame H3 clip.
    2. Anchor the Suno vocal word span [w_start, w_end] directly to [raw_t0, raw_t1].
    3. Use local ±4-frame Vowel-Formant Guided Frame Selection so open-vowel peaks pick naturally wide-open
       H3 frames and consonant valleys pick naturally closed-mouth H3 frames!
    """
    n_raw = len(raw_mo)
    t_raw_grid = np.arange(n_raw) / float(FPS)
    n_target = min(len(aud_env), int(round(target_dur * FPS)))
    n_out = int(round(out_dur * FPS))

    # Require both mouth opening AND dynamic mouth movement so static smiles are excluded
    dmo = np.convolve(np.abs(np.gradient(raw_mo)), np.ones(5) / 5.0, mode="same")
    mo_thresh = max(0.020, 0.18 * float(np.percentile(raw_mo, 95)))
    active_idx = np.where((raw_mo >= mo_thresh) & (dmo >= 0.003))[0]
    if len(active_idx) < 12:
        active_idx = np.where(raw_mo >= mo_thresh)[0]
    raw_t0 = float(active_idx[0]) / FPS if len(active_idx) else 0.04
    raw_t1 = float(active_idx[-1]) / FPS if len(active_idx) else min(2.50, t_raw_grid[-1])

    w_start = max(0.04, float(words_rel[0][0])) if words_rel else 0.08
    w_end = min(target_dur - 0.02, float(words_rel[-1][1])) if words_rel else (target_dur - 0.10)
    w_mid = 0.5 * (w_start + w_end)

    t_out_target = np.arange(n_target) / float(FPS)
    v_target = vowel_mod[:n_target]

    raw_mid_base = 0.5 * (raw_t0 + raw_t1)
    best_pw = (-1.0, raw_t0, raw_mid_base, raw_t1)
    for ds in np.linspace(-0.08, 0.12, 9):
        for dm in np.linspace(-0.22, 0.22, 19):
            for de in np.linspace(-0.12, 0.08, 9):
                ts = np.clip(raw_t0 + ds, 0.0, raw_t1 - 0.8)
                te = np.clip(raw_t1 + de, ts + 1.0, raw_t1 + 0.08)
                tm = np.clip(raw_mid_base + dm, ts + 0.30 * (te - ts), te - 0.30 * (te - ts))
                knots_x = [0.0, w_start, w_mid, w_end, target_dur]
                knots_y = [max(0.0, ts - 0.04), ts, tm, te, min(t_raw_grid[-1], te + (target_dur - w_end))]
                tq = np.interp(t_out_target, knots_x, knots_y)
                mw = np.interp(tq, t_raw_grid, raw_mo)
                if mw.std() < 1e-5:
                    continue
                c = float(np.corrcoef(v_target, mw)[0, 1])
                if c > best_pw[0]:
                    best_pw = (c, float(ts), float(tm), float(te))

    corr_pw, ts, tm, te = best_pw
    t_out_full = np.arange(n_out) / float(FPS)
    knots_x_full = [0.0, w_start, w_mid, w_end, out_dur]
    knots_y_full = [
        max(0.0, ts - 0.04),
        ts,
        tm,
        te,
        min(t_raw_grid[-1], te + (out_dur - w_end)),
    ]
    t_query_full = np.interp(t_out_full, knots_x_full, knots_y_full)

    # Strictly monotonic (j >= prev_idx) local frame selection so head/hand/camera motion NEVER stutters backward:
    peak_raw_mo = float(np.percentile(raw_mo[active_idx], 92)) if len(active_idx) else 0.13
    min_raw_mo = float(np.percentile(raw_mo[active_idx], 8)) if len(active_idx) else 0.005
    chosen_indices = []
    prev_idx = 0
    max_active_frame = min(n_raw - 1, int(round(raw_t1 * FPS)) + 2)

    for k in range(n_out):
        base_idx = min(n_raw - 1, max(prev_idx, int(round(t_query_full[k] * FPS))))
        t_cur = k / float(FPS)
        if w_start - 0.04 <= t_cur <= w_end + 0.04:
            lo = max(max(0, prev_idx - 2), base_idx - 6)
            hi = min(max_active_frame, base_idx + 6)
            if hi >= lo:
                desired_mo = min_raw_mo + vowel_mod[k] * (peak_raw_mo - min_raw_mo)
                best_j = base_idx
                best_cost = 999.0
                for j in range(lo, hi + 1):
                    mo_err = abs(raw_mo[j] - desired_mo)
                    if vowel_mod[k] > 0.45 and raw_mo[j] < 0.48 * peak_raw_mo:
                        mo_err += 0.08
                    elif vowel_mod[k] < 0.15 and raw_mo[j] > 0.38 * peak_raw_mo:
                        mo_err += 0.07
                    step_pen = 0.004 * abs(j - base_idx) + 0.004 * abs(j - prev_idx) + (0.006 if j < prev_idx else 0.0)
                    cost = mo_err + step_pen
                    if cost < best_cost:
                        best_cost = cost
                        best_j = j
                base_idx = best_j
        else:
            # Outside active words (after w_end): smoothly advance into H3's natural closed-mouth tail (>= raw_t1)
            if t_cur > w_end + 0.04:
                tail_start = min(n_raw - 1, int(round(raw_t1 * FPS)) + 2)
                base_idx = max(prev_idx, tail_start + int(round((t_cur - w_end) * FPS)))
                base_idx = min(n_raw - 1, base_idx)
        prev_idx = base_idx
        chosen_indices.append(base_idx)

    warped_frames = [raw_frames_bgr[idx].copy() for idx in chosen_indices]
    return warped_frames, corr_pw, (round(raw_t0, 2), round(raw_t1, 2)), (round(ts, 2), round(tm, 2), round(te, 2))


def apply_768p_anatomical_lip_drive(
    frame_bgr: np.ndarray,
    pts: np.ndarray,
    cur_mo: float,
    target_mo: float,
    closed_frame_bgr: np.ndarray,
    closed_pts: np.ndarray,
    who: str,
) -> np.ndarray:
    """Stage 2 (Scheme A): Strictly Diffeomorphic (|d(disp_y)/dy| < 0.44) 1344x768 Lip-Only Drive.
    - Never touches the chin or vintage microphone below outer lower lip (pts[17]).
    - Guaranteed zero horizontal seam creases and zero double-moustache folding.
    """
    H, W = frame_bgr.shape[:2]
    fh = max(12.0, abs(pts[152, 1] - pts[10, 1]))
    fw = max(12.0, abs(pts[454, 0] - pts[234, 0]))

    delta_mo = target_mo - cur_mo
    if abs(delta_mo) < 0.004:
        return frame_bgr

    mouth_cx = 0.5 * (pts[61, 0] + pts[291, 0])
    mouth_cy = 0.5 * (pts[13, 1] + pts[14, 1])
    mouth_w = max(8.0, abs(pts[291, 0] - pts[61, 0]))

    # Strictly bound ROI above the microphone (stop just below outer lower lip pts[17])
    rx1 = max(0, int(mouth_cx - 0.36 * fw))
    rx2 = min(W, int(mouth_cx + 0.36 * fw))
    ry1 = max(0, int(mouth_cy - 0.14 * fh))
    ry2 = min(H, int(max(pts[17, 1], pts[14, 1]) + 0.075 * fh))
    if rx2 - rx1 < 8 or ry2 - ry1 < 8:
        return frame_bgr

    rh, rw = ry2 - ry1, rx2 - rx1
    grid_x, grid_y = np.meshgrid(np.arange(rw, dtype=np.float32), np.arange(rh, dtype=np.float32))

    # Center Gaussian strictly on the lower lip body (midpoint of inner lip 14 and outer lip 17)
    ll_x = 0.5 * (pts[14, 0] + pts[17, 0]) - rx1
    ll_y = 0.5 * (pts[14, 1] + pts[17, 1]) - ry1
    sigma_x = max(6.0, 0.45 * mouth_w)
    sigma_y = max(6.0, 0.095 * fh)

    # Enforce strict diffeomorphism bound: |dy_lower_lip| <= 0.68 * sigma_y so |d(disp_y)/dy| <= 0.41 < 1
    max_safe_dy = 0.68 * sigma_y
    gain = 1.25 if who == "b" else 1.18
    dy_lower_lip = float(np.clip(delta_mo * fh * gain, -max_safe_dy, max_safe_dy))

    # Protect metallic/bright microphone pixels near bottom of ROI from any displacement
    roi_bgr = frame_bgr[ry1:ry2, rx1:rx2]
    roi_hsv = cv2.cvtColor(roi_bgr, cv2.COLOR_BGR2HSV)
    is_mic = ((roi_hsv[:, :, 1] < 48) & (roi_hsv[:, :, 2] > 105) & (grid_y > (pts[14, 1] - ry1))).astype(np.float32)
    mic_keep = 1.0 - cv2.GaussianBlur(is_mic, (0, 0), sigmaX=2.5)

    w_ll = np.exp(-0.5 * (((grid_x - ll_x) / sigma_x) ** 2 + ((grid_y - ll_y) / sigma_y) ** 2)) * mic_keep
    disp_y = w_ll * dy_lower_lip

    map_x = grid_x
    map_y = np.clip(grid_y - disp_y, 0.0, float(rh - 1))

    out = frame_bgr.copy()
    warped_roi = cv2.remap(roi_bgr, map_x, map_y, interpolation=cv2.INTER_CUBIC, borderMode=cv2.BORDER_REFLECT_101)

    if delta_mo > 0.012:
        inner_pts = pts[INNER_LIP_RING].copy()
        inner_pts[:, 0] -= rx1
        inner_pts[:, 1] -= ry1
        ic = np.mean(inner_pts, axis=0, keepdims=True)
        inner_pts[:, 1] = ic[0, 1] + (inner_pts[:, 1] - ic[0, 1]) * (1.0 + delta_mo * 3.2) + 0.30 * dy_lower_lip

        inner_mask = np.zeros((rh, rw), dtype=np.float32)
        cv2.fillConvexPoly(inner_mask, cv2.convexHull(inner_pts.astype(np.int32)), 1.0)
        inner_mask = (cv2.GaussianBlur(inner_mask, (0, 0), sigmaX=max(2.0, 0.04 * mouth_w)) * mic_keep)[:, :, None]

        dark_cavity = (warped_roi.astype(np.float32) * 0.42).astype(np.uint8)
        alpha_cav = np.clip(delta_mo * 3.8, 0.0, 0.48) * inner_mask
        warped_roi = (dark_cavity.astype(np.float32) * alpha_cav + warped_roi.astype(np.float32) * (1.0 - alpha_cav)).astype(np.uint8)
    elif delta_mo < -0.008 and cur_mo > 0.016:
        # Affine-align the native 768p closed-mouth reference frame onto the current lip corners & upper lip
        src_tri = np.array([
            closed_pts[61],
            closed_pts[291],
            closed_pts[2],
        ], dtype=np.float32)
        dst_tri = np.array([
            pts[61] - [rx1, ry1],
            pts[291] - [rx1, ry1],
            pts[2] - [rx1, ry1],
        ], dtype=np.float32)
        M_aff = cv2.getAffineTransform(src_tri, dst_tri)
        closed_roi = cv2.warpAffine(
            closed_frame_bgr, M_aff, (rw, rh),
            flags=cv2.INTER_CUBIC, borderMode=cv2.BORDER_REFLECT_101
        )

        outer_pts = pts[OUTER_LIP_RING].copy()
        outer_pts[:, 0] -= rx1
        outer_pts[:, 1] -= ry1
        lip_mask = np.zeros((rh, rw), dtype=np.float32)
        cv2.fillConvexPoly(lip_mask, cv2.convexHull(outer_pts.astype(np.int32)), 1.0)
        lip_mask = (cv2.GaussianBlur(lip_mask, (0, 0), sigmaX=max(2.5, 0.06 * mouth_w)) * mic_keep)[:, :, None]

        # Match local brightness of closed_roi to warped_roi inside the lip region
        m_bool = lip_mask[:, :, 0] > 0.2
        if np.any(m_bool):
            for c_idx in range(3):
                s_mean = float(np.mean(closed_roi[:, :, c_idx][m_bool])) + 1e-4
                t_mean = float(np.mean(warped_roi[:, :, c_idx][m_bool])) + 1e-4
                closed_roi[:, :, c_idx] = np.clip(closed_roi[:, :, c_idx].astype(np.float32) * (t_mean / s_mean), 0, 255).astype(np.uint8)

        close_ratio = float(np.clip((-delta_mo) / max(0.020, cur_mo), 0.0, 0.92))
        alpha_close = close_ratio * lip_mask
        warped_roi = (closed_roi.astype(np.float32) * alpha_close + warped_roi.astype(np.float32) * (1.0 - alpha_close)).astype(np.uint8)

    out[ry1:ry2, rx1:rx2] = warped_roi
    return out


def verify_lipcheck(clip_mp4: str, who: str, two_shot: bool, landmarker) -> dict:
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", clip_mp4, "-ac", "1", "-ar", "16000", "-f", "f32le", "-"],
        capture_output=True
    ).stdout
    wav = np.frombuffer(raw, dtype=np.float32)

    cap = cv2.VideoCapture(clip_mp4)
    frames_rgb = []
    while True:
        ret, fr = cap.read()
        if not ret:
            break
        frames_rgb.append(cv2.cvtColor(fr, cv2.COLOR_BGR2RGB))
    cap.release()

    n = len(frames_rgb)
    aud_env, vowel_mod = compute_vowel_syllable_envelope(wav, n)
    _, mouth_open = detect_faces_in_frames(frames_rgb, who, two_shot, landmarker)

    def calc_corr(target_curve):
        a = target_curve[:n] - target_curve[:n].mean()
        m = mouth_open[:n] - mouth_open[:n].mean()
        denom = (np.linalg.norm(a) * np.linalg.norm(m)) + 1e-9
        c0 = float(np.dot(a, m) / denom)
        best = (c0, 0)
        for k in range(-4, 5):
            a2 = a[max(0, k) : n + min(0, k)]
            m2 = m[max(0, -k) : n - max(0, k)]
            c = float(np.dot(a2, m2) / ((np.linalg.norm(a2) * np.linalg.norm(m2)) + 1e-9))
            if c > best[0]:
                best = (c, k)
        return c0, best[0], int(best[1] * 1000 / FPS)

    rms_c0, rms_best, rms_lag = calc_corr(aud_env)
    vow_c0, vow_best, vow_lag = calc_corr(vowel_mod)
    dyn_mo = float(np.mean(np.abs(np.diff(mouth_open[: n - 6]))))
    return {
        "frames": n,
        "rms_corr_at_0": round(rms_c0, 3),
        "vowel_corr_at_0": round(vow_c0, 3),
        "best_lag_ms": vow_lag,
        "mouth_open_max": round(float(mouth_open.max()), 4),
        "mouth_open_min": round(float(mouth_open.min()), 4),
        "syllable_dyn": round(dyn_mo, 4),
    }


def process_clip(
    cid: str,
    raw_mp4: str,
    out_mp4: str,
    vocal_wav_full: str,
    edl_t0: float,
    edl_t1: float,
    words_rel: list,
    who: str,
    two_shot: bool,
    landmarker,
    work_audio_out: str,
):
    target_dur = edl_t1 - edl_t0
    out_dur = target_dur + 0.25

    step = SR // FPS
    n_out = int(round(out_dur * FPS))
    req_samples = max(int(round(out_dur * SR)), n_out * step + SR // 4)
    wav_full, _ = librosa.load(vocal_wav_full, sr=SR, mono=True)
    s_samp = max(0, int(round(edl_t0 * SR)))
    e_samp = min(len(wav_full), s_samp + req_samples)
    wav_slice = np.zeros(req_samples, dtype=np.float32)
    seg = wav_full[s_samp:e_samp]
    wav_slice[: len(seg)] = seg

    sample_gate = np.zeros_like(wav_slice)
    for ws, we in words_rel:
        i0 = max(0, int((ws - 0.03) * SR))
        i1 = min(len(sample_gate), int((we + 0.05) * SR))
        if i1 > i0:
            sample_gate[i0:i1] = 1.0
    sample_gate = gaussian_filter1d(sample_gate, sigma=int(0.010 * SR), mode="constant", cval=0.0)
    wav_clean = wav_slice * np.clip(sample_gate, 0.0, 1.0)
    sf.write(work_audio_out, wav_clean[: int(round(out_dur * SR))], SR)

    aud_env, vowel_mod = compute_vowel_syllable_envelope(wav_clean, n_out)

    cap = cv2.VideoCapture(raw_mp4)
    raw_frames_bgr = []
    while True:
        ret, fr = cap.read()
        if not ret:
            break
        raw_frames_bgr.append(fr)
    cap.release()
    H, W = raw_frames_bgr[0].shape[:2]

    raw_rgb = [cv2.cvtColor(f, cv2.COLOR_BGR2RGB) for f in raw_frames_bgr]
    raw_lms, raw_mo = detect_faces_in_frames(raw_rgb, who, two_shot, landmarker)
    closed_raw_idx = int(np.argmin(raw_mo))

    # Stage 1: Word-Anchored Active-Span Time-Warp + F1/F2 Vowel-Formant Frame Selection
    warped_bgr, corr_pw, raw_span, knots = optimize_word_anchored_warp(
        raw_frames_bgr, raw_mo, aud_env, vowel_mod, words_rel, target_dur, out_dur
    )

    # Stage 2: Vowel-Formant Guided 768p Anatomical Lip/Jaw Open-Close Drive
    warped_rgb = [cv2.cvtColor(f, cv2.COLOR_BGR2RGB) for f in warped_bgr]
    lms_seq, mo_warped = detect_faces_in_frames(warped_rgb, who, two_shot, landmarker)

    peak_mo = max(0.145 if who == "b" else 0.155, min(0.175, float(np.percentile(mo_warped, 95)) * 1.25))
    # Drive mouth directly from the sharp 0.0 <-> 1.0 vowel syllable curve so every word opens and closes crisply!
    target_mo_seq = vowel_mod * peak_mo
    target_mo_seq[vowel_mod < 0.06] = 0.0

    out_frames_bgr = []
    for i in range(n_out):
        driven = apply_768p_anatomical_lip_drive(
            frame_bgr=warped_bgr[i],
            pts=lms_seq[i],
            cur_mo=float(mo_warped[i]),
            target_mo=float(target_mo_seq[i]),
            closed_frame_bgr=raw_frames_bgr[closed_raw_idx],
            closed_pts=raw_lms[closed_raw_idx],
            who=who,
        )
        out_frames_bgr.append(driven)

    tmp_vid = out_mp4 + ".tmp_v.mp4"
    fourcc = cv2.VideoWriter_fourcc(*"mp4v")
    vw = cv2.VideoWriter(tmp_vid, fourcc, FPS, (W, H))
    for fr in out_frames_bgr:
        vw.write(fr)
    vw.release()

    subprocess.run([
        "ffmpeg", "-y", "-v", "error",
        "-i", tmp_vid, "-i", work_audio_out,
        "-c:v", "libx264", "-crf", "18", "-preset", "fast", "-pix_fmt", "yuv420p",
        "-c:a", "aac", "-b:a", "192k", "-shortest", out_mp4
    ], check=True)
    os.remove(tmp_vid)
    return corr_pw, raw_span, knots


